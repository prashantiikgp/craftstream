const write = bool.fromEnvironment('WRITE_BRAND');
const previewDir = '../.playwright-mcp/brand';

/// Launcher icons use the light-mode colours: the launcher can't follow the in-app light/dark switch.

void main() {
  late ThemeEngine engine;
  late DesignTokens light, dark;

  setUpAll(() async {
    TestWidgetsFlutterBinding.ensureInitialized();
    engine = ThemeEngine(await loadThemeRules());
    light = engine.light;
    dark = engine.dark;
  });

  Map<String, String> textFiles(DesignTokens t) {
    final brand = hexOf(t.brand), onBrand = hexOf(t.onBrand), ink = hexOf(t.ink), brandInk = hexOf(t.brandInk);
    final mark = toPathData(markCmds());
    // Adaptive icons are 108 dp with a 66 dp safe circle: the mark gets 56 dp, centred.
    final fg = toPathData(markCmds(), scale: 0.56, dx: 26, dy: 26.5);
    const gen = '<!-- Generated by test/shared/brand/brand_assets_test.dart. Do not edit. -->';
    return {
      'assets/brand/craftstream-mark.svg':
          '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">$gen<path fill="$brand" fill-rule="evenodd" d="$mark"/></svg>\n',
      'assets/brand/craftstream-mark-mono.svg':
          '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">$gen<path fill="currentColor" fill-rule="evenodd" d="$mark"/></svg>\n',
      'assets/brand/craftstream-app-icon.svg':
          '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">$gen<rect width="100" height="100" rx="22.5" fill="$brand"/>'
              '<path fill="$onBrand" fill-rule="evenodd" d="${toPathData(markCmds(), scale: 0.62, dx: 19, dy: 20)}"/></svg>\n',
      'assets/brand/craftstream-app-icon-maskable.svg':
          '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">$gen<rect width="100" height="100" fill="$brand"/>'
              '<path fill="$onBrand" fill-rule="evenodd" d="${toPathData(markCmds(), scale: 0.5, dx: 25, dy: 26)}"/></svg>\n',
      'assets/brand/craftstream-lockup.svg':
          '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 440 100">$gen<path fill="$brand" fill-rule="evenodd" d="$mark"/>'
              '<text x="128" y="72" font-family="Poppins, sans-serif" font-weight="700" font-size="62" letter-spacing="-1.2">'
              '<tspan fill="$ink">Craft</tspan><tspan fill="$brandInk">Stream</tspan></text></svg>\n',
      'android/app/src/main/res/drawable/ic_launcher_foreground.xml': '''<?xml version="1.0" encoding="utf-8"?>
$gen
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillColor="$onBrand" android:fillType="evenOdd" android:pathData="$fg"/>
</vector>
''',
      'android/app/src/main/res/drawable/ic_launcher_background.xml': '''<?xml version="1.0" encoding="utf-8"?>
$gen
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillColor="$brand" android:pathData="M0 0 L108 0 L108 108 L0 108 Z"/>
</vector>
''',
      'android/app/src/main/res/mipmap-anydpi-v26/ic_launcher.xml': '''<?xml version="1.0" encoding="utf-8"?>
$gen
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
    <monochrome android:drawable="@drawable/ic_launcher_foreground"/>
</adaptive-icon>
''',
    };
  }

  // name -> (pixel size, painter)
  Map<String, (int, void Function(Canvas, Size))> pngFiles(DesignTokens t) {
    void rounded(Canvas c, Size s) => paintAppIcon(c, s, bg: t.brand, fg: t.onBrand);
    void legacy(Canvas c, Size s) => paintAppIcon(c, s, bg: t.brand, fg: t.onBrand, inset: s.width / 24);
    void maskable(Canvas c, Size s) =>
        paintAppIcon(c, s, bg: t.brand, fg: t.onBrand, cornerFraction: 0, markFraction: 0.5);
    return {
      for (final (dir, px) in const [('mdpi', 48), ('hdpi', 72), ('xhdpi', 96), ('xxhdpi', 144), ('xxxhdpi', 192)])
        'android/app/src/main/res/mipmap-$dir/ic_launcher.png': (px, legacy),
      'web/favicon.png': (32, rounded),
      'web/icons/Icon-192.png': (192, rounded),
      'web/icons/Icon-512.png': (512, rounded),
      'web/icons/Icon-maskable-192.png': (192, maskable),
      'web/icons/Icon-maskable-512.png': (512, maskable),
    };
  }

  test('brand SVG and Android vector files are fresh', () async {
    for (final MapEntry(key: path, value: content) in textFiles(light).entries) {
      final f = File(path);
      if (write) {
        f.parent.createSync(recursive: true);
        f.writeAsStringSync(content);
      }
      expect(f.existsSync(), isTrue, reason: '$path is missing: regenerate (see top of this file)');
      expect(f.readAsStringSync(), content, reason: '$path is stale: regenerate (see top of this file)');
    }
  });

  test('launcher and web icons exist at the right pixel sizes', () async {
    for (final MapEntry(key: path, value: (px, paint)) in pngFiles(light).entries) {
      final f = File(path);
      if (write) f.writeAsBytesSync(await renderPng(Size.square(px.toDouble()), paint));
      expect(f.existsSync(), isTrue, reason: path);
      expect(pngSize(f.readAsBytesSync()), (px, px), reason: path);
    }
  });

  test('previews for the design-system page', () async {
    if (!write) return;
    await loadPoppins();
    Directory(previewDir).createSync(recursive: true);
    for (final (name, t) in [('light', light), ('dark', dark)]) {
      await writePreview('mark-$name.png', const Size(256, 256), (c, s) {
        c.drawColor(t.bg, BlendMode.src);
        MarkPainter(color: t.brand).paint(c..translate(32, 32), const Size(192, 192));
      });
      await writePreview('lockup-$name.png', const Size(720, 160), (c, s) {
        c.drawColor(t.bg, BlendMode.src);
        paintLockup(c, const Offset(40, 40), 80, t);
      });
      for (final kind in SpotKind.values) {
        await writePreview('spot-${kind.name}-$name.png', const Size(480, 360), (c, s) {
          c.drawColor(t.bg, BlendMode.src);
          SpotPainter(kind, BrandPalette.of(t)).paint(c, s);
        });
      }
      await writePreview('sheet-$name.png', const Size(1200, 980), (c, s) => paintSheet(c, s, t, icon: light));
    }
    await writePreview('app-icon.png', const Size(512, 512), pngFiles(light)['web/icons/Icon-512.png']!.$2);
    await writePreview('app-icon-maskable.png', const Size(512, 512), pngFiles(light)['web/icons/Icon-maskable-512.png']!.$2);
  });
}

Future<Uint8List> renderPng(Size size, void Function(Canvas, Size) paint) async {
  final recorder = ui.PictureRecorder();
  paint(Canvas(recorder), size);
  final image = await recorder.endRecording().toImage(size.width.round(), size.height.round());
  final data = await image.toByteData(format: ui.ImageByteFormat.png);
  return data!.buffer.asUint8List();
}

Future<void> writePreview(String name, Size size, void Function(Canvas, Size) paint) async =>
    File('$previewDir/$name').writeAsBytesSync(await renderPng(size, paint));

/// Width and height from a PNG's IHDR chunk.
(int, int) pngSize(Uint8List bytes) {
  final d = ByteData.sublistView(bytes);
  return (d.getUint32(16), d.getUint32(20));
}

Future<void> loadPoppins() async {
  final loader = FontLoader(BrandLockup.wordmarkFamily)
    ..addFont(Future.value(ByteData.sublistView(File('assets/fonts/Poppins-Bold.ttf').readAsBytesSync())));
  await loader.load();
}

/// The lockup painted directly (same proportions as BrandLockup) so previews need no widget tree.
double paintLockup(Canvas c, Offset at, double height, DesignTokens t) {
  MarkPainter(color: t.brand).paint(c..save()..translate(at.dx, at.dy), Size.square(height));
  c.restore();
  final style = TextStyle(
    fontFamily: BrandLockup.wordmarkFamily,
    fontWeight: FontWeight.w700,
    fontSize: height * 0.62,
    height: 1,
    letterSpacing: -height * 0.012,
    color: t.ink,
  );
  final tp = TextPainter(
    text: TextSpan(style: style, children: [
      const TextSpan(text: 'Craft'),
      TextSpan(text: 'Stream', style: TextStyle(color: t.brandInk)),
    ]),
    textDirection: TextDirection.ltr,
  )..layout();
  tp.paint(c, at + Offset(height * 1.28, (height - tp.height) / 2));
  return height * 1.28 + tp.width;
}

/// Everything on one page: lockup, mark sizes, app icon, the four spot illustrations and all poster motifs.
void paintSheet(Canvas c, Size s, DesignTokens t, {required DesignTokens icon}) {
  c.drawColor(t.bg, BlendMode.src);
  paintLockup(c, const Offset(40, 36), 64, t);
  var x = 40.0;
  for (final px in [16.0, 24.0, 32.0, 48.0, 96.0]) {
    MarkPainter(color: t.brand).paint(c..save()..translate(x, 216 - px), Size.square(px));
    c.restore();
    x += px + 28;
  }
  for (final px in [32.0, 96.0]) {
    c.save();
    c.translate(x, 216 - px);
    paintAppIcon(c, Size.square(px), bg: icon.brand, fg: icon.onBrand);
    c.restore();
    x += px + 28;
  }
  for (var i = 0; i < SpotKind.values.length; i++) {
    final r = Rect.fromLTWH(40 + i * 284.0, 250, 264, 198);
    c.drawRRect(RRect.fromRectAndRadius(r, const Radius.circular(14)), Paint()..color = t.card);
    c.save();
    c.translate(r.left, r.top);
    SpotPainter(SpotKind.values[i], BrandPalette.of(t)).paint(c, r.size);
    c.restore();
  }
  for (var i = 0; i < PosterMotif.values.length; i++) {
    final motif = PosterMotif.values[i];
    final r = Rect.fromLTWH(40 + (i % 3) * 380.0, 480 + (i ~/ 3) * 236.0, 360, 202.5);
    final (wash, accent) = ProductPosterPlaceholder.colorsFor(motif, t);
    c.save();
    c.clipRRect(RRect.fromRectAndRadius(r, const Radius.circular(14)));
    c.translate(r.left, r.top);
    PosterPainter(motif: motif, wash: wash, accent: accent, disc: t.card).paint(c, r.size);
    c.restore();
  }
}
