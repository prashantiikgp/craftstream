// Brand files on disk (SVG sources, Android adaptive icon, launcher + web PNGs) are generated from the same
// geometry and palette the app paints with. Normal runs check they are present and fresh; regenerate with
//
//   flutter test test/shared/brand/brand_assets_test.dart --dart-define=WRITE_BRAND=true
//
// which also writes previews to ../.playwright-mcp/brand/ (gitignored).
